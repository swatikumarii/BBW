/**
 * generatePaymentId function is responsible to generate the unique payment ID
 * @param  {Integer} orderId Order Id
 * @return {string} Payment ID
 */
function generatePaymentId(orderId) {
    var date = new Date();
    return orderId + date.getHours() + date.getMinutes() + date.getSeconds();
}

/**
 * generateHash function is responsible to generate the SHA256 encrypted string
 * @param  {Object} hashData hash Data
 * @return {string} encoded string
 */
function generateHash(hashData) {
    var Bytes = require('dw/util/Bytes');
    var MessageDigest = require('dw/crypto/MessageDigest');
    var Encoding = require('dw/crypto/Encoding');
    var digestSHA256 = new MessageDigest(MessageDigest.DIGEST_SHA_256);
    return Encoding.toHex(digestSHA256.digestBytes(new Bytes(hashData, 'UTF-8')));
}


/**
 * prepareUrlParam function is responsible to generate the URL param
 * @param  {Object} requestObj url request
 * @return {string} url parameter
 */
function prepareUrlParam(requestObj) {
    var formBody = [];
    for (var property in requestObj) {
        var encodedKey = (property);
        var encodedValue = (requestObj[property]);
        formBody.push(encodedKey + '=' + encodedValue);
    }
    return formBody.join('&');
}

/**
 * generateEghlPaymentUrl function is responsible to generate the eGHL payment redirect URL
 * @param  {Object} order Order Object
 * @param  {string} paymentId Payment Id
 * @return {URL} eGHLPaymentUrl
 */
function generateEghlPaymentUrl(order, paymentId) {
    var eghlServiceCredentials = eghlApi.getServiceCredentials();

    var serviceID = eghlServiceCredentials.user;
    var merchantReturnUrl = eGHLPreference.merchantReturnUrl.toString() + '?ID=' + order.getOrderNo() + '&orderToken=' + order.orderToken;
    merchantReturnUrl = merchantReturnUrl.replace('&', ';');
    var merchantCallBackUrl = eGHLPreference.merchantCallBackUrl.toString();
    var amount = order.totalGrossPrice.value.toFixed(2);
    // var amount = 0.14;
    var currencyCode = eGHLPreference.currencyCode;
    var pageTimeOut = eGHLPreference.pageTimeOut || '';

    // Prepare request for hash data
    var hashData = eghlServiceCredentials.password + serviceID + paymentId + merchantReturnUrl + merchantCallBackUrl + amount + currencyCode + pageTimeOut;

    // Prepare request for url param
    var requestObj = {
        TransactionType: eGHLPreference.transactionType, // SALE
        PymtMethod: eGHLPreference.paymentMethod, //ANY
        ServiceID: serviceID, // Provided by eGHL
        PaymentID: paymentId,  // Generated by us combination of order id and time
        OrderNumber: order.getOrderNo(), // Order number for merchant refrence
        PaymentDesc: order.getOrderNo(),
        MerchantReturnURL: merchantReturnUrl, // Return URL on which customer can land
        Amount: amount, // Order total gross price
        CurrencyCode: currencyCode, // Currency code set for this transaction
        HashValue: generateHash(hashData), // SHA 256 encrypted key
        CustName: order.billingAddress.fullName, // Customer name from billing address
        CustEmail: order.customerEmail, // Customer email from order
        CustPhone: order.billingAddress.phone, // Customer phone from billing address
        MerchantName: eGHLPreference.merchantName || '', // merhcant name to be shown in eGHL site
        MerchantCallBackURL: merchantCallBackUrl, // Call back url to which eGHL sent payment status
        PageTimeout: pageTimeOut // Transaction time out on merchant site
    };

    var urlParam = prepareUrlParam(requestObj);
    return eghlServiceCredentials.baseUrl + '?' + urlParam;
}

/**
 * generateResponseHashValue function is responsible to return the hash value
 * @param  {Object} requestObj order request data
 * @return {string} hash value
 */
function generateResponseHashValue(requestObj) {
    return generateHash(requestObj);
}

/**
 * eghlQueryRequest function is responsible to generate the query param for Payment Query
 * @param  {Object} order order object
 * @return {string} query param
 */
function eghlQueryRequest(order) {
    var eghlServiceCredentials = eghlApi.getServiceCredentials();
    var orderAmount = order.totals.plainGrandTotal.value + '.00';

    // request data to generate hash value
    var hashRequest = eghlServiceCredentials.password + eghlServiceCredentials.user + order.eghlPaymentId + orderAmount + eGHLPreference.currencyCode;

    // create query request
    var requestObject = {
        TransactionType: eGHLPreference.queryTransactionType,
        PymtMethod: order.eghlPaymentMethod,
        ServiceID: eghlServiceCredentials.user,
        PaymentID: order.eghlPaymentId,
        Amount: order.totals.plainGrandTotal.value,
        CurrencyCode: eGHLPreference.currencyCode,
        HashValue: generateHash(hashRequest)
    };

    return prepareUrlParam(requestObject);
}

/**
 * prepareJsonObject function is responsible to generate the JSON array from query param
 * @param  {string} data query parameter
 * @return  {Object} Json Object of query param
 */
function prepareJsonObject(data) {
    var pairs = data.split('&');
    var result = {};
    pairs.forEach(function (pair) {
        // eslint-disable-next-line no-param-reassign
        pair = pair.split('=');
        result[pair[0]] = decodeURIComponent(pair[1] || '');
    });

    return JSON.parse(JSON.stringify(result));
}

/**
 * renderCustomer function is responsible to render the customer on order success page
 * @param  {Object} order Order object
 * @param  {Object} result Place order object
 * @param  {Object} orderStatus Order status object
 * @param  {Object} server Server data
 * @param  {request} req current request
 * @param  {response} res Response to customer
 */
function renderCustomer(order, result, orderStatus, server, req, res) {
    var config = {
        numberOfLineItems: '*'
    };

    var currentLocale;
    if ('locale' in req && req.locale.id) {
        currentLocale = Locale.getLocale(req.locale.id);
    }

    var orderModel = new OrderModel(
        order,
        { config: config, countryCode: currentLocale.country, containerView: 'order' }
    );
    var passwordForm;

    var reportingURLs = reportingUrlsHelper.getOrderReportingURLs(order);
    var viewData = res.getViewData();
    viewData.isThankYouPage = true;
    res.setViewData(viewData);
    if (!req.currentCustomer.profile) {
        passwordForm = server.forms.getForm('newPasswords');
        passwordForm.clear();
        res.render('checkout/confirmation/confirmation', {
            order: orderModel,
            returningCustomer: false,
            passwordForm: passwordForm,
            reportingURLs: reportingURLs,
            orderUUID: order.getUUID(),
            orderStatus: orderStatus
        });
    } else {
        res.render('checkout/confirmation/confirmation', {
            order: orderModel,
            returningCustomer: true,
            reportingURLs: reportingURLs,
            orderUUID: order.getUUID(),
            orderStatus: orderStatus
        });
    }
    req.session.raw.custom.orderID = req.querystring.ID; // eslint-disable-line no-param-reassign
}

/**
 * pendingOrder function is responsible to update the order status to pending
 * @param  {Object} order Order object
 * @param  {boolean} isEhlCallback eghlCallback flag
 * @param  {Object} server Server data
 * @param  {Object} req Request data
 * @param  {Object} res Response Data
 * @param  {pointer} next pointer
 */
function pendingOrder(order, isEhlCallback, server, req, res, next) {
    var co = require('dw/object/CustomObjectMgr');
    var result = { error: false, message: '' };
    var queryParam = req.httpParameterMap;
    var paymentTransaction = order.paymentInstrument.getPaymentTransaction();
    try {
        Transaction.begin();
        paymentTransaction.paymentInstrument.paymentTransaction.transactionID = queryParam.TxnID.value;
        order.custom.eghlPaymentId = queryParam.PaymentID.value; // eslint-disable-line no-param-reassign
        order.custom.eghlTxnId = queryParam.TxnID.value; // eslint-disable-line no-param-reassign
        order.custom.eghlPaymentMethod = paymentTransaction.paymentInstrument.custom.eghlPaymentMethod; // eslint-disable-line no-param-reassign
        paymentTransaction.paymentInstrument.custom.eghlLog = queryParam;

        var checkEghlNotofication = co.getCustomObject('eghlNotification', queryParam.ID.value);
        if (checkEghlNotofication) {
            checkEghlNotofication.custom.eghlLog = queryParam;
        } else {
            var updatEghlNotifiaction = co.createCustomObject('eghlNotification', queryParam.ID.value);
            updatEghlNotifiaction.custom.eghlLog = queryParam;
        }

        Transaction.commit();
        if (!isEhlCallback) {
            var orderStatus = queryParam.TxnStatus.value;
            renderCustomer(order, result, orderStatus, server, req, res, next);
        }
    } catch (e) {
        logger.error('Error while updating the pending payment data' + e);
        result.error = true;
        result.message = Resource.msg('common.error.msg', 'eghl', null);
    }
}

/**
 * failOrder function is responsible to update the order status to fail
 * @param  {Object} order Order object
 * @param  {boolean} isEhlCallback eghlCallback flag
 * @param  {Object} server Server data
 * @param  {Request} req Request Object
 * @param  {Response} res Response Object
 * @param  {pointer} next pointer
 */
function failOrder(order, isEhlCallback, server, req, res, next) {
    var result = { error: false, message: '' };
    var queryParam = req.httpParameterMap;
    var paymentTransaction = order.paymentInstrument.getPaymentTransaction();
    try {
        Transaction.begin();
        var failOrderStatus = OrderMgr.failOrder(order, true);
        if (failOrderStatus == Status.ERROR) {
            throw new Error();
        }
        paymentTransaction.paymentInstrument.paymentTransaction.transactionID = queryParam.TxnID.value;
        order.custom.eghlPaymentId = queryParam.PaymentID.value; // eslint-disable-line no-param-reassign
        order.custom.eghlTxnId = queryParam.TxnID.value; // eslint-disable-line no-param-reassign
        order.custom.eghlPaymentMethod = paymentTransaction.paymentInstrument.custom.eghlPaymentMethod; // eslint-disable-line no-param-reassign
        paymentTransaction.paymentInstrument.custom.eghlLog = queryParam;
        Transaction.commit();

        // Trigger order place email to user
        if (order.getCustomerEmail()) {
            COHelpers.sendFailOrderEmail(order, req.locale.id);
        }
        if (!isEhlCallback) {
            var orderStatus = queryParam.TxnStatus.value;
            renderCustomer(order, result, orderStatus, server, req, res, next);
        }
    } catch (e) {
        logger.error('Error while updating the order staus to Fail' + e);
        result.error = true;
        result.message = Resource.msg('common.error.msg', 'eghl', null);
    }
}

/**
 * placeOrder function is responsible to update the order staus accoding to eGHL txn status
 * @param  {Object} order order object
 * @param  {boolean} isEhlCallback eghlCallback flag
 * @param  {Object} server Server data
 * @param  {request} req  request object
 * @param  {response} res response object
 * @param  {pointer} next pointer
 */
function placeOrder(order, isEhlCallback, server, req, res, next) {
    var result = { error: false, message: '' };
    var queryParam = req.httpParameterMap;
    var paymentTransaction = order.paymentInstrument.getPaymentTransaction();
    var qwikcilverHelpers = require('*/cartridge/scripts/helpers/qwikcilverHelpers');
    var isGiftProductAvailable = qwikcilverHelpers.validateGiftProduct(order);
    var qwikcilverApis = require('*/cartridge/scripts/service/qwikcilverApis');
    var currentLocale;
    if ('locale' in req && req.locale.id) {
        currentLocale = Locale.getLocale(req.locale.id);
    } else {
        currentLocale = 'en_MY';
    }
    var giftCardAPIResult;
    var giftCardAPIRedeemResult;
    try {
        // Redeem Qwikcilver Gift Card
        if (order.getPaymentInstruments('GIFT_CERTIFICATE').length > 0) {
            logger.error('EGHL:Order is going in to gift certificate line item in the eghlhelper file for order id {0}', order.orderNo);
            giftCardAPIRedeemResult = qwikcilverApis.redeemGiftCards(order);

            if (giftCardAPIRedeemResult && giftCardAPIRedeemResult.status == 'OK' && giftCardAPIRedeemResult.object) {
                var redeemGiftCard = JSON.parse(giftCardAPIRedeemResult.object);
                if (redeemGiftCard.ResponseCode !== 0 && redeemGiftCard.Cards && redeemGiftCard.Cards.length > 0) {
                    for (var i = 0; i < redeemGiftCard.Cards.length; i++) {
                        result.error = true;
                        result.message = redeemGiftCard.Cards[i].ResponseMessage;
                    }
                }
            } else if (giftCardAPIRedeemResult && giftCardAPIRedeemResult.errorMessage) {
                if ('status' in giftCardAPIRedeemResult && giftCardAPIRedeemResult.getStatus().equals('SERVICE_UNAVAILABLE')) {
                    result.error = true;
                    result.message = Resource.msg('qwikcilver.service.unavailable', 'qwikcilver', null);
                } else if (giftCardAPIRedeemResult.msg !== 'Connection reset') {
                    var redeemErrorMessageObj = JSON.parse(giftCardAPIRedeemResult.errorMessage);
                    result.error = true;
                    result.message = redeemErrorMessageObj.message;
                } else {
                    result.error = true;
                    result.message = Resource.msg('error.technical', 'checkout', null);
                }
            }
        }

        Transaction.begin();
        logger.info('EGHL:Order is placed from helper file with order id {0}', order.orderNo);
        var placeOrderStatus = OrderMgr.placeOrder(order);
        if (placeOrderStatus == Status.ERROR) {
            throw new Error();
        }
        order.setConfirmationStatus(Order.CONFIRMATION_STATUS_CONFIRMED);

        order.setExportStatus(Order.EXPORT_STATUS_READY);
        order.setPaymentStatus(Order.PAYMENT_STATUS_PAID);
        paymentTransaction.paymentInstrument.paymentTransaction.transactionID = queryParam.TxnID.value;
        order.custom.eghlPaymentId = queryParam.PaymentID.value; // eslint-disable-line no-param-reassign
        order.custom.eghlTxnId = queryParam.TxnID.value; // eslint-disable-line no-param-reassign
        order.custom.eghlPaymentMethod = paymentTransaction.paymentInstrument.custom.eghlPaymentMethod; // eslint-disable-line no-param-reassign
        paymentTransaction.paymentInstrument.custom.eghlLog = queryParam;
        Transaction.commit();

        // Handles Gift payment authorization
        var handlePaymentResult = COHelpers.handlePayments(order, order.orderNo);
        if (handlePaymentResult.error) {
            result.error = true;
            result.message = Resource.msg('error.technical', 'checkout', null);
        }

        if (giftCardAPIRedeemResult) {
            var redeemedGiftCard = JSON.parse(giftCardAPIRedeemResult.object);
            if (redeemedGiftCard.ResponseCode == 0) {
                qwikcilverHelpers.saveGiftCardDetails(order, redeemedGiftCard, 'Redeemed');
            }
        }

        // Send GiftCard Email
        // eslint-disable-next-line no-undef
        var log = dw.system.Logger.getLogger('QwikcilverService');
        if (isGiftProductAvailable) {
            for (var index = 0; index < order.productLineItems.length; index++) {
                    // Create GiftCard
                    giftCardAPIResult = qwikcilverApis.createGiftCards(order, index);
                    if (giftCardAPIResult && giftCardAPIResult.errorMessage) {
                        if ('status' in giftCardAPIResult && giftCardAPIResult.getStatus().equals('SERVICE_UNAVAILABLE')) {
                            result.error = true;
                            result.message = Resource.msg('qwikcilver.service.unavailable', 'qwikcilver', null);
                        } else if (giftCardAPIResult.msg !== 'Connection reset') {
                            var errorMessageObj = JSON.parse(giftCardAPIResult.errorMessage);
                            result.error = true;
                            result.message = errorMessageObj.message;
                        } else {
                            result.error = true;
                            result.message = Resource.msg('error.technical', 'checkout', null);
                        }
                    }
                if (giftCardAPIResult && giftCardAPIResult.status === 'OK' && giftCardAPIResult.object) {
                    var giftCard = JSON.parse(giftCardAPIResult.object);
                    if (giftCard.ResponseCode === 0) {
                        qwikcilverHelpers.saveGiftCardDetails(order, giftCard, 'Created', index);
                        qwikcilverHelpers.sendGiftCardEmail(order, currentLocale, false, true, index);
                    } else {
                        qwikcilverHelpers.sendGiftCardEmail(order, currentLocale, false, false, index);
                        log.info('Error while Creating a Gift Card for OrderNo: {0}', order.orderNo);
                        log.info('Gift Card Email is Not Sent to the Customer for OrderID: {0} for Item Number {1}', order.orderNo, index);
                        if (index === order.productLineItems.length - 1) {
                            renderCustomer(order, result, 'CardIssueFailed', server, req, res, next);
                        }
                        return;
                    }
                } else if (!giftCardAPIResult && !giftCardAPIRedeemResult && isGiftProductAvailable) {
                    qwikcilverHelpers.sendGiftCardEmail(order, currentLocale, false, false, index);
                    log.info('Error while Creating a Gift Card for OrderNo: {0}', order.orderNo);
                    log.info('Gift Card Email is Not Sent to the Customer for OrderID: {0} for Item Number {1}', order.orderNo, index);
                    renderCustomer(order, result, 'CardIssueFailed', server, req, res, next);
                    return;
                }
            }
        } else if (order.getCustomerEmail()) {
            COHelpers.sendConfirmationEmail(order, req.locale.id);
        }

        if (!isEhlCallback) {
            var orderStatus = queryParam.TxnStatus.value;
            renderCustomer(order, result, orderStatus, server, req, res, next);
        }
    } catch (e) {
        Transaction.wrap(function () { OrderMgr.failOrder(order, true); });
        logger.error('Error while placing the order. Error response is' + e);
        result.error = true;
        result.message = Resource.msg('common.error.msg', 'eghl', null);
    }
}

